const fs = require('fs');
const path = require('path');

const HTML_PATH = path.join(__dirname, 'index.html');
const OUT_PATH = path.join(__dirname, 'locale-translations.js');

const html = fs.readFileSync(HTML_PATH, 'utf8');
const languagesStart = html.indexOf('const languages = [');
const languagesEnd = html.indexOf('];', languagesStart) + 2;
const translationsStart = html.indexOf('const translations = {', languagesEnd);
const providerStart = html.indexOf('// Language Provider Component', translationsStart);
const translationsEnd = html.lastIndexOf('};', providerStart) + 2;
const declarations = html.slice(languagesStart, languagesEnd)
  + '\n' + html.slice(translationsStart, translationsEnd)
  + '\nreturn { languages, translations };';
const { languages, translations } = new Function(declarations)();

const PH_PRE = 'ZPH';
const PH_SUF = 'HPZ';
let phId = 0;

function mask(text) {
  const map = [];
  const masked = text.replace(/\{([^{}]+)\}/g, (_, name) => {
    const token = `${PH_PRE}${++phId}${PH_SUF}`;
    map.push([token, `{${name}}`]);
    return token;
  });
  return { masked, map };
}

function unmask(text, map) {
  let out = text;
  for (const [token, original] of map) {
    out = out.includes(token) ? out.split(token).join(original) : `${out} ${original}`;
  }
  return out;
}

async function translateOne(text, tl, retries = 4) {
  const params = new URLSearchParams({ client: 'gtx', sl: 'en', tl, dt: 't', q: text });
  for (let attempt = 1; attempt <= retries; attempt++) {
    try {
      const res = await fetch(`https://translate.googleapis.com/translate_a/single?${params}`);
      if (!res.ok) {
        if (res.status === 429 || res.status >= 500) {
          await new Promise(r => setTimeout(r, 2500 * attempt));
          continue;
        }
        throw new Error(`HTTP ${res.status}`);
      }
      const payload = await res.json();
      return (payload[0] || []).map(p => p[0] || '').join('');
    } catch (err) {
      if (attempt === retries) throw err;
      await new Promise(r => setTimeout(r, 1500 * attempt));
    }
  }
}

(async () => {
  const enKeys = Object.keys(translations.en);
  const result = {};
  const langs = languages.filter(l => l.code !== 'en');

  console.log(`Found ${langs.length} languages to process`);
  console.log(`English has ${enKeys.length} keys total\n`);

  for (const lang of langs) {
    const existing = translations[lang.code] || {};
    const missing = enKeys.filter(k => existing[k] === undefined);
    if (missing.length === 0) {
      console.log(`   ${lang.code} (${lang.name}) already complete`);
      continue;
    }
    console.log(`${lang.code} (${lang.name}): ${missing.length} missing keys`);

    const out = {};
    let done = 0;
    for (const key of missing) {
      const { masked, map } = mask(translations.en[key]);
      try {
        const translated = await translateOne(masked, lang.code);
        out[key] = unmask(translated, map);
      } catch (err) {
        console.error(`   x ${lang.code}/${key}: ${err.message}`);
        out[key] = translations.en[key];
      }
      done++;
      if (done % 20 === 0) process.stdout.write(`   ${done}/${missing.length}\r`);
      await new Promise(r => setTimeout(r, 120));
    }
    result[lang.code] = out;
    console.log(`\nOK ${lang.code} done (${Object.keys(out).length} translated)`);
  }

  fs.writeFileSync(
    OUT_PATH,
    `// Auto-generated by translate-fill.js\nwindow.STATIC_TRANSLATIONS = ${JSON.stringify(result, null, 2)};\n`,
    'utf8'
  );

  const total = Object.values(result).reduce((s, o) => s + Object.keys(o).length, 0);
  console.log(`\nDone. Wrote ${OUT_PATH}`);
  console.log(`   ${total} strings across ${Object.keys(result).length} locales`);
})().catch(err => {
  console.error('Fatal:', err);
  process.exitCode = 1;
});